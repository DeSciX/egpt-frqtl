#!/usr/bin/env bash
# Replace an adopted KB source dir with a FRAQTL `make publish-corpus` output dir and
# record its provenance.
#
#   scripts/refresh-kb.sh <publish-corpus-output-dir> <General|frqtl_sdk>
#
# Only the two adopted KBs are refreshed this way; HowToSee, Personas and Recipes are
# authored here. The destination is read from .descix/manifests/<KB>.json. Every
# markdown file must carry the publish-corpus GENERATED stamp; provenance is read from
# those stamps, never typed by hand. Links to dev.descix.net are rewritten to
# descix.net, because this repo is the PROD app.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
. "$ROOT/scripts/lib/tree.sh"

PROVENANCE="$ROOT/.descix/kb-provenance.json"

[ $# -eq 2 ] || die "usage: scripts/refresh-kb.sh <publish-corpus-output-dir> <General|frqtl_sdk>"
SRC=$1
KB=$2
case "$KB" in
  General|frqtl_sdk) ;;
  *) die "$KB is not an adopted KB (General, frqtl_sdk); HowToSee, Personas and Recipes are edited in place" ;;
esac

MANIFEST="$ROOT/.descix/manifests/$KB.json"
[ -f "$MANIFEST" ] || die "$MANIFEST is missing"
KB_PATH=$(jq -er '.sources | if length == 1 then .[0].path else error("expected exactly one source") end' "$MANIFEST") \
  || die "$MANIFEST must have exactly one source with a path"
DEST="$ROOT/$KB_PATH"

[ -d "$SRC" ] || die "$SRC is not a directory"
SRC=$(cd "$SRC" && pwd)
[ "$SRC" != "$DEST" ] || die "source is $KB_PATH itself"

# Parse every markdown stamp BEFORE touching the destination.
sources_json='[]'
unstamped_json='[]'
md_count=0
while IFS= read -r -d '' f; do
  rel=${f#$SRC/}
  case "$rel" in
    *.md)
      md_count=$((md_count + 1))
      head -1 "$f" | grep -q '^<!-- GENERATED by `make publish-corpus`' \
        || die "$rel has no publish-corpus GENERATED stamp — $SRC is not a publish-corpus output dir"
      src_line=$(sed -n 2p "$f")
      date_line=$(sed -n 3p "$f")
      [[ "$src_line" =~ ^[[:space:]]+source:\ (.+)\ @\ ([0-9a-f]{7,40})\ \((.+)\ repo\)$ ]] \
        || die "$rel stamp line 2 is malformed: $src_line"
      s_path=${BASH_REMATCH[1]}; s_sha=${BASH_REMATCH[2]}; s_repo=${BASH_REMATCH[3]}
      [[ "$date_line" =~ ^[[:space:]]+committed:\ ([0-9]{4}-[0-9]{2}-[0-9]{2})\ --\>$ ]] \
        || die "$rel stamp line 3 is malformed: $date_line"
      s_date=${BASH_REMATCH[1]}
      sources_json=$(jq -c --arg file "$rel" --arg source "$s_path" --arg sha "$s_sha" --arg repo "$s_repo" --arg committed "$s_date" \
        '. + [{file: $file, upstream_repo: $repo, source: $source, source_sha: $sha, committed: $committed}]' <<<"$sources_json")
      ;;
    *)
      unstamped_json=$(jq -c --arg file "$rel" '. + [$file]' <<<"$unstamped_json")
      ;;
  esac
done < <(find "$SRC" -type f ! -name .DS_Store -print0 | LC_ALL=C sort -z)

[ "$md_count" -gt 0 ] || die "$SRC holds no markdown — not a publish-corpus output dir"
repos=$(jq -r '[.[].upstream_repo] | unique | join(",")' <<<"$sources_json")
[[ "$repos" != *,* ]] || die "$SRC mixes upstream repos: $repos"

replace_tree "$SRC" "$DEST"

REWRITES=0
while IFS= read -r -d '' f; do
  n=$(grep -o 'dev\.descix\.net' "$f" | wc -l | tr -d ' ' || true)
  if [ "$n" -gt 0 ]; then
    sed -i.refresh-bak 's/dev\.descix\.net/descix.net/g' "$f" && rm "$f.refresh-bak"
    REWRITES=$((REWRITES + n))
  fi
done < <(find "$DEST" -type f -print0)
! grep -rq 'dev\.descix\.net' "$DEST" || die "dev.descix.net survived the host rewrite in $KB_PATH"

FILE_COUNT=$(tree_file_count "$DEST")
TREE_SHA=$(tree_sha256 "$DEST")

[ -f "$PROVENANCE" ] || echo '{}' > "$PROVENANCE"
jq --arg kb "$KB" --arg path "$KB_PATH" --arg repo "$repos" \
  --argjson sources "$sources_json" --argjson unstamped "$unstamped_json" \
  --argjson count "$FILE_COUNT" --arg tree "$TREE_SHA" --argjson rewrites "$REWRITES" \
  '.[$kb] = {path: $path, upstream_repo: $repo, sources: $sources, unstamped_files: $unstamped,
             host_rewrites_dev_to_prod: $rewrites, file_count: $count, tree_sha256: $tree,
             refreshed_by_script: "scripts/refresh-kb.sh"}' \
  "$PROVENANCE" > "$PROVENANCE.tmp"
mv "$PROVENANCE.tmp" "$PROVENANCE"

echo "$KB_PATH refreshed from $repos: $FILE_COUNT files ($md_count stamped), $REWRITES dev.descix.net links rewritten, tree sha256 $TREE_SHA"
echo "wrote ${PROVENANCE#$ROOT/}"
