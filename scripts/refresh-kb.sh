#!/usr/bin/env bash
# Replace an adopted KB source dir with a FRAQTL `make publish-corpus` output dir and
# record its provenance.
#
#   scripts/refresh-kb.sh <publish-corpus-output-dir> <General|frqtl_sdk>
#
# Only the two adopted KBs are refreshed this way; HowToSee, Personas and Recipes are
# authored here. The destination is read from .descix/manifests/<KB>.json. Every
# markdown file in the input must carry the publish-corpus GENERATED stamp; provenance is
# read from those stamps into .descix/kb-provenance.json, and the stamps are stripped from
# the published KB text — provenance lives only in kb-provenance.json. Links to
# dev.descix.net are rewritten to descix.net, because this repo is the PROD app.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
. "$ROOT/scripts/lib/tree.sh"

PROVENANCE="$ROOT/.descix/kb-provenance.json"

# The publish-corpus stamp block (FRAQTL scripts/publish-corpus.mjs::stamp), defined once,
# as Perl regexes. It is parsed, stripped and hunted for with these and nothing else.
STAMP_HEAD='<!-- GENERATED by `make publish-corpus` from \.descix/corpus — do not edit\.'
STAMP_SOURCE='[ \t]*source: (.+) @ ([0-9a-f]{7,40}) \((.+) repo\)'
STAMP_DATE='[ \t]*committed: ([0-9]{4}-[0-9]{2}-[0-9]{2}) -->'
STAMP_BLOCK="\\A${STAMP_HEAD}\\n${STAMP_SOURCE}\\n${STAMP_DATE}\\n\\n"
export STAMP_HEAD STAMP_SOURCE STAMP_DATE STAMP_BLOCK

# Fail loud if any stamp text survives anywhere under $1.
check_no_stamp() {
  local dir=$1 label=$2 survivors
  survivors=$(find "$dir" -type f -print0 | xargs -0 perl -ne '
    print "$ARGV:$.: $_" if /$ENV{STAMP_HEAD}|$ENV{STAMP_SOURCE}|$ENV{STAMP_DATE}/;
    close ARGV if eof;') || die "stamp survivor scan of $label failed"
  [ -z "$survivors" ] || die "publish-corpus stamp text survived in $label:
$survivors"
}

[ $# -eq 2 ] || die "usage: scripts/refresh-kb.sh <publish-corpus-output-dir> <General|frqtl_sdk>"
SRC=$1
KB=$2
case "$KB" in
  General|frqtl_sdk) ;;
  *) die "$KB is not an adopted KB (General, frqtl_sdk); HowToSee, Personas and Recipes are edited in place" ;;
esac

MANIFEST="$ROOT/.descix/manifests/$KB.json"
[ -f "$MANIFEST" ] || die "$MANIFEST is missing"
KB_PATH=$(jq -er '.sources | if length == 1 then .[0].path else error("expected exactly one source") end' "$MANIFEST") \
  || die "$MANIFEST must have exactly one source with a path"
DEST="$ROOT/$KB_PATH"

[ -d "$SRC" ] || die "$SRC is not a directory"
SRC=$(cd "$SRC" && pwd)
[ "$SRC" != "$DEST" ] || die "source is $KB_PATH itself"

STAGE=$(mktemp -d "${TMPDIR:-/tmp}/refresh-kb.XXXXXX")
trap 'rm -rf "$STAGE"' EXIT
cp -R "$SRC/." "$STAGE/" || die "copy $SRC -> $STAGE failed"
find "$STAGE" -name .DS_Store -delete

# Parse every markdown stamp from the input and strip it from the staged copy, BEFORE
# touching the destination.
sources_json='[]'
unstamped_json='[]'
md_count=0
while IFS= read -r -d '' f; do
  rel=${f#$STAGE/}
  case "$rel" in
    *.md)
      md_count=$((md_count + 1))
      fields=$(perl -0777 -ne '
        /\A$ENV{STAMP_HEAD}\n/ or exit 3;
        /$ENV{STAMP_BLOCK}/ or exit 4;
        print join("\t", $1, $2, $3, $4);' "$f") && rc=0 || rc=$?
      case "$rc" in
        0) ;;
        3) die "$rel has no publish-corpus GENERATED stamp — $SRC is not a publish-corpus output dir" ;;
        4) die "$rel stamp block is malformed: $(head -3 "$f")" ;;
        *) die "$rel stamp parse failed (perl exit $rc)" ;;
      esac
      IFS=$'\t' read -r s_path s_sha s_repo s_date <<<"$fields"
      sources_json=$(jq -c --arg file "$rel" --arg source "$s_path" --arg sha "$s_sha" --arg repo "$s_repo" --arg committed "$s_date" \
        '. + [{file: $file, upstream_repo: $repo, source: $source, source_sha: $sha, committed: $committed}]' <<<"$sources_json")
      perl -0777 -i -pe 's/$ENV{STAMP_BLOCK}// or die "stamp strip matched nothing\n"' "$f" \
        || die "$rel: stamp strip failed"
      ;;
    *)
      unstamped_json=$(jq -c --arg file "$rel" '. + [$file]' <<<"$unstamped_json")
      ;;
  esac
done < <(find "$STAGE" -type f -print0 | LC_ALL=C sort -z)

[ "$md_count" -gt 0 ] || die "$SRC holds no markdown — not a publish-corpus output dir"
repos=$(jq -r '[.[].upstream_repo] | unique | join(",")' <<<"$sources_json")
[[ "$repos" != *,* ]] || die "$SRC mixes upstream repos: $repos"

REWRITES=0
while IFS= read -r -d '' f; do
  n=$(grep -o 'dev\.descix\.net' "$f" | wc -l | tr -d ' ' || true)
  if [ "$n" -gt 0 ]; then
    sed -i.refresh-bak 's/dev\.descix\.net/descix.net/g' "$f" && rm "$f.refresh-bak"
    REWRITES=$((REWRITES + n))
  fi
done < <(find "$STAGE" -type f -print0)
! grep -rq 'dev\.descix\.net' "$STAGE" || die "dev.descix.net survived the host rewrite of $SRC"

check_no_stamp "$STAGE" "the staged copy of $SRC"
replace_tree "$STAGE" "$DEST"
check_no_stamp "$DEST" "$KB_PATH"

FILE_COUNT=$(tree_file_count "$DEST")
TREE_SHA=$(tree_sha256 "$DEST")

[ -f "$PROVENANCE" ] || echo '{}' > "$PROVENANCE"
jq --arg kb "$KB" --arg path "$KB_PATH" --arg repo "$repos" \
  --argjson sources "$sources_json" --argjson unstamped "$unstamped_json" \
  --argjson count "$FILE_COUNT" --arg tree "$TREE_SHA" --argjson rewrites "$REWRITES" \
  '.[$kb] = {path: $path, upstream_repo: $repo, sources: $sources, unstamped_files: $unstamped,
             host_rewrites_dev_to_prod: $rewrites, file_count: $count, tree_sha256: $tree,
             refreshed_by_script: "scripts/refresh-kb.sh"}' \
  "$PROVENANCE" > "$PROVENANCE.tmp"
mv "$PROVENANCE.tmp" "$PROVENANCE"

echo "$KB_PATH refreshed from $repos: $FILE_COUNT files ($md_count stamps recorded and stripped), $REWRITES dev.descix.net links rewritten, tree sha256 $TREE_SHA"
echo "wrote ${PROVENANCE#$ROOT/}"
