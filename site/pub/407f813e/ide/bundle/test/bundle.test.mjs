/**
 * bundle.test.mjs — Bite-2 MERGE GATES for lib/shim/bundle/.
 *
 *   (a) STORE-zip round-trip: bytes written by zip.js are readable by an
 *       INDEPENDENT standard unzip (the system /usr/bin/unzip) AND by our own
 *       reader — verifying central directory + CRCs + STORE method.
 *   (b) bundle → envelope → bundle IDENTITY (E1 ferry proof).
 *   (c) .frqnb projection conformance driven off notebook CELL_ATTRS (every attr
 *       the projection sets is a known CELL_ATTR, and serialize→parse preserves
 *       them — so a new CELL_ATTR flows through the projection automatically).
 *   (d) manifest NEVER re-lists envelope fields: an envelope with an EXTRA future
 *       field survives the bundle round-trip verbatim (proving the {...envelope}
 *       ferry, not a hand-enumerated key set), and `source` is NOT in the manifest.
 *
 * Run: node --test lib/shim/bundle/test/bundle.test.mjs
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';
import { mkdtempSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';

const __dirname = dirname(fileURLToPath(import.meta.url));
const BUNDLE_DIR = resolve(__dirname, '..');
const SHIM_DIR = resolve(__dirname, '../..');

const { zipStore, unzipStore, crc32, textBytes, bytesText } =
    await import(join(BUNDLE_DIR, 'zip.js'));
const { assembleBundle, importBundle, FILE_MANIFEST_JSON, FILE_EXPERIMENT_JS, FILE_EXPERIMENT_FRQNB } =
    await import(join(BUNDLE_DIR, 'index.js'));
const { buildManifest } = await import(join(BUNDLE_DIR, 'manifest.js'));
const { parse, CELL_ATTRS } = await import(join(SHIM_DIR, 'notebook/format.js'));

// ── A sample recipe source + envelope (the exact shape STUDIO's Save builds) ──
const RECIPE_SRC =
    '// Generated by FRQTL codegen — <ts>\n' +
    'function buildExperiment(exp) {\n' +
    '  exp.init({ dimension: 2, wavelengthScale: 8 });\n' +
    '  exp.addObject("PointSource", {"x":300,"y":200,"diameter":24});\n' +
    '}\n' +
    "if (typeof module !== 'undefined' && module.exports) { module.exports = { buildExperiment: buildExperiment }; }\n" +
    "else if (typeof window !== 'undefined') { window.buildExperiment = buildExperiment; }\n";

function sampleEnvelope(extra) {
    return Object.assign({
        id: 'mod_test1',
        name: 'Fountain Pool',
        language: 'javascript',
        source: RECIPE_SRC,
        scripts: ['objects/setup/setupSphereEmitter3D.js'],   // DX-3: setup-factory delta
        templateId: '_empty',
        kind: 'frqtl',
        createdAt: '2026-07-21T00:00:00.000Z',
        updatedAt: '2026-07-21T00:00:00.000Z',
        schemaVersion: 4,
        renderState: {
            version: 1, renderer: 'three', engine: 'wasm', egpt3D: true, seed: '42',
            backdropVisible: false,
            camera: { orbit: null, preset: 'down-barrel' },
            render: [{ key: 'shape', value: 'sphere' }, { key: 'godrays', value: 0.8 }],
            pageControls: []
        }
    }, extra || {});
}

// ─────────────────────────────────────────────────────────────────────────────
// (a) STORE-zip round-trip vs an INDEPENDENT unzip
// ─────────────────────────────────────────────────────────────────────────────

describe('(a) STORE-zip round-trip', function () {

    test('own reader round-trips arbitrary entries (incl. UTF-8 + binary)', function () {
        const entries = [
            { name: 'experiment.js', bytes: textBytes('function buildExperiment(exp){}\n') },
            { name: 'nested/áé–💡.txt', bytes: textBytes('unicode ☃ body') },
            { name: 'preview.png', bytes: new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0, 255, 128, 7]) }
        ];
        const zip = zipStore(entries);
        const back = unzipStore(zip);
        assert.strictEqual(back.length, entries.length);
        for (let i = 0; i < entries.length; i++) {
            assert.strictEqual(back[i].name, entries[i].name, 'name[' + i + ']');
            assert.deepEqual(Array.from(back[i].bytes), Array.from(entries[i].bytes), 'bytes[' + i + ']');
        }
    });

    test('crc32 matches the known IEEE test vector for "123456789"', function () {
        // Standard CRC-32/ISO-HDLC check value = 0xCBF43926.
        assert.strictEqual(crc32(textBytes('123456789')), 0xCBF43926);
    });

    test('bytes are readable by the system /usr/bin/unzip (independent verifier)', function () {
        const { zipBytes } = assembleBundle(sampleEnvelope(), { sdkVersion: '0.1.7' });
        const dir = mkdtempSync(join(tmpdir(), 'frqtl-bundle-'));
        try {
            const zipPath = join(dir, 'bundle.zip');
            writeFileSync(zipPath, zipBytes);
            // `unzip -l` lists the central directory (exits 0 only if it parses).
            const listing = execFileSync('unzip', ['-l', zipPath], { encoding: 'utf8' });
            assert.ok(/experiment\.js/.test(listing), 'unzip -l lists experiment.js');
            assert.ok(/manifest\.json/.test(listing), 'unzip -l lists manifest.json');
            // Extract experiment.js via unzip -p and compare bytes exactly.
            const extracted = execFileSync('unzip', ['-p', zipPath, FILE_EXPERIMENT_JS]);
            assert.strictEqual(extracted.toString('utf8'), RECIPE_SRC,
                'system unzip extracts experiment.js byte-identically');
            // `unzip -t` tests all CRCs (exits non-zero on any CRC failure).
            const tested = execFileSync('unzip', ['-t', zipPath], { encoding: 'utf8' });
            assert.ok(/No errors detected/.test(tested), 'unzip -t reports no CRC errors');
        } finally {
            rmSync(dir, { recursive: true, force: true });
        }
    });

    test('unzipStore FAIL-LOUD on a non-ZIP buffer', function () {
        assert.throws(() => unzipStore(new Uint8Array([1, 2, 3, 4])), /End Of Central Directory/);
    });
});

// ─────────────────────────────────────────────────────────────────────────────
// (b) bundle → envelope → bundle identity
// ─────────────────────────────────────────────────────────────────────────────

describe('(b) bundle round-trip identity', function () {

    test('importBundle(assembleBundle(E)) recovers E exactly', function () {
        const E = sampleEnvelope();
        const { zipBytes } = assembleBundle(E, { sdkVersion: '0.1.7' });
        const { envelope } = importBundle(zipBytes);
        assert.deepEqual(envelope, E, 'recovered envelope must equal the original');
    });

    test('(DX-3) scripts delta survives the round-trip + is embedded in index.html', function () {
        const E = sampleEnvelope();
        const { files, zipBytes } = assembleBundle(E, { sdkVersion: '0.1.7' });
        // (i) round-trip preserves scripts on the recovered envelope.
        const { envelope } = importBundle(zipBytes);
        assert.deepEqual(envelope.scripts, ['objects/setup/setupSphereEmitter3D.js']);
        // (ii) index.html embeds the scripts inline + forwards them to bootRecipe.
        const indexHtml = bytesText(files.find((f) => f.name === 'index.html').bytes);
        assert.ok(/const SCRIPTS = \["objects\/setup\/setupSphereEmitter3D\.js"\];/.test(indexHtml),
            'index.html inlines SCRIPTS');
        assert.ok(/bootRecipe\(mount, src, \{ renderState: RENDER_STATE, scripts: SCRIPTS \}\)/.test(indexHtml),
            'index.html forwards scripts to bootRecipe');
    });

    test('preview bytes survive the round-trip', function () {
        const preview = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 13, 10, 26, 10, 1, 2, 3]);
        const { zipBytes } = assembleBundle(sampleEnvelope(), { sdkVersion: '0.1.7', previewPngBytes: preview });
        const { envelope, previewPngBytes } = importBundle(zipBytes);
        assert.deepEqual(Array.from(previewPngBytes), Array.from(preview), 'preview bytes preserved');
        assert.strictEqual(envelope.name, 'Fountain Pool');
    });

    test('re-assembling the recovered envelope yields byte-identical files', function () {
        const E = sampleEnvelope();
        const b1 = assembleBundle(E, { sdkVersion: '0.1.7' });
        const E2 = importBundle(b1.zipBytes).envelope;
        const b2 = assembleBundle(E2, { sdkVersion: '0.1.7' });
        assert.deepEqual(Array.from(b2.zipBytes), Array.from(b1.zipBytes),
            'deterministic: bundle→envelope→bundle is byte-stable');
    });
});

// ─────────────────────────────────────────────────────────────────────────────
// (c) .frqnb projection conformance driven off CELL_ATTRS
// ─────────────────────────────────────────────────────────────────────────────

describe('(c) .frqnb projection conformance', function () {

    const CELL_ATTR_KEYS = new Set(CELL_ATTRS.map((a) => a.key));

    function frqnbOf(env) {
        const { files } = assembleBundle(env, { sdkVersion: '0.1.7' });
        const f = files.find((x) => x.name === FILE_EXPERIMENT_FRQNB);
        return bytesText(f.bytes);
    }

    test('projection parses back into markdown + module + canvas cells', function () {
        const nb = parse(frqnbOf(sampleEnvelope()));
        const types = nb.cells.map((c) => c.type);
        assert.deepEqual(types, ['markdown', 'module', 'canvas']);
    });

    test('module cell carries the recipe source verbatim', function () {
        const nb = parse(frqnbOf(sampleEnvelope()));
        const mod = nb.cells.find((c) => c.type === 'module');
        assert.strictEqual(mod.name, './experiment.js');
        assert.strictEqual(mod.body, RECIPE_SRC, 'recipe source round-trips through the .frqnb');
    });

    test('every attr the canvas projection sets is a KNOWN CELL_ATTR (no schema drift)', function () {
        const nb = parse(frqnbOf(sampleEnvelope()));
        const canvas = nb.cells.find((c) => c.type === 'canvas');
        // The parsed canvas cell carries a body + type + the attrs we set; assert
        // every non-body key is a declared CELL_ATTR — a projection that invented
        // an off-schema key would fail here.
        for (const key of Object.keys(canvas)) {
            if (key === 'body') { continue; }
            assert.ok(CELL_ATTR_KEYS.has(key),
                'canvas cell key "' + key + '" is not a declared CELL_ATTR — projection drift');
        }
    });

    test('render intent (render3d/cameraPreset/renderOptions/setup/stage/seed) ferries via serialize→parse', function () {
        const nb = parse(frqnbOf(sampleEnvelope()));
        const canvas = nb.cells.find((c) => c.type === 'canvas');
        assert.strictEqual(canvas.setup, './experiment.js#buildExperiment');
        assert.strictEqual(canvas.stage, '600x400');
        assert.strictEqual(canvas.seed, '42');
        assert.strictEqual(canvas.render3d, true, 'egpt3D → render3d');
        assert.strictEqual(canvas.cameraPreset, 'down-barrel', 'camera.preset → cameraPreset');
        assert.deepEqual(canvas.renderOptions, { shape: 'sphere', godrays: 0.8 },
            'render[] → renderOptions opts bag');
    });
});

// ─────────────────────────────────────────────────────────────────────────────
// (d) manifest ferries the envelope — an extra future field survives
// ─────────────────────────────────────────────────────────────────────────────

describe('(d) manifest ferry (no field re-enumeration)', function () {

    test('an UNKNOWN future envelope field survives the bundle round-trip', function () {
        const E = sampleEnvelope({ futureField: { nested: [1, 2, 3] }, anotherNew: 'hello' });
        const { zipBytes } = assembleBundle(E, { sdkVersion: '0.1.7' });
        const { envelope } = importBundle(zipBytes);
        assert.deepEqual(envelope.futureField, { nested: [1, 2, 3] }, 'unknown object field ferried');
        assert.strictEqual(envelope.anotherNew, 'hello', 'unknown scalar field ferried');
    });

    test('manifest carries every non-source envelope field but NOT source', function () {
        const E = sampleEnvelope({ futureField: 7 });
        const manifest = buildManifest(E, { sdkVersion: '0.1.7' });
        assert.ok(!('source' in manifest), 'source is NOT in the manifest (owned by experiment.js)');
        // every non-source envelope key is present verbatim
        for (const k of Object.keys(E)) {
            if (k === 'source') { continue; }
            assert.deepEqual(manifest[k], E[k], 'envelope field "' + k + '" ferried into manifest');
        }
        assert.strictEqual(manifest.sdkVersion, '0.1.7');
        assert.deepEqual(manifest.descix, {});
    });

    test('buildManifest FAIL-LOUD without sdkVersion', function () {
        assert.throws(() => buildManifest(sampleEnvelope(), {}), /sdkVersion is REQUIRED/);
    });
});
